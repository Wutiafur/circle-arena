def save_crash_report(exc_type, exc_value, exc_traceback):
    BUG_REPORT_DIR.mkdir(exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    report_path = BUG_REPORT_DIR / f"crash_{timestamp}.txt"
    traceback_text = "".join(traceback.format_exception(exc_type, exc_value, exc_traceback))
    report_lines = [
        "Circle Crash Report",
        f"Time: {datetime.now().isoformat(timespec='seconds')}",
        f"Python: {sys.version}",
        f"Pygame: {pygame.version.ver}",
        f"Executable: {sys.executable}",
        f"Working Directory: {Path.cwd()}",
        f"Game File: {Path(__file__).resolve()}",
        "",
        "Settings:",
        json.dumps(GAME_SETTINGS, ensure_ascii=False, indent=2),
        "",
    ]
    snapshot_text = build_crash_snapshot_text()
    if snapshot_text:
        report_lines.append("Last Battle Snapshot:")
        report_lines.append(snapshot_text)
        report_lines.append("")
    report_lines.append("Traceback:")
    report_lines.append(traceback_text)
    report_path.write_text("\n".join(report_lines), encoding="utf-8")
    return report_path


def build_crash_snapshot_text():
    game_state = runtime._LIVE_GAME_STATE
    if game_state is None:
        return ""
    lines = []
    try:
        lines.append(f"elapsed_time: {game_state.get('elapsed_time', 0.0):.2f} s")
        lines.append(f"speed_multiplier: {runtime._LIVE_SPEED_MULTIPLIER:g}")
        lines.append(f"pause: {bool(game_state.get('_pause_flag', False))}")
        characters = game_state.get("characters", [])
        alive = [c for c in characters if getattr(c, "alive", False)]
        lines.append(f"total_characters: {len(characters)}  alive: {len(alive)}")
        lines.append(f"projectiles: {len(game_state.get('projectiles', []))}  design_effects: {len(game_state.get('design_effects', []))}")
        lines.append(f"weapon_orbs: {len(game_state.get('weapon_orbs', []))}  kill_banners: {len(game_state.get('kill_banners', []))}")
        for c in alive[:24]:
            lines.append(
                f"  {c.job_name:28s} hp={c.hp:8.1f}/{c.max_hp:8.1f} mp={c.mp:6.1f} pos=({c.pos.x:7.2f},{c.pos.y:7.2f}) damageDealt={c.damageDealt:.0f} damageTaken={c.damageTaken:.0f}"
            )
        if len(alive) > 24:
            lines.append(f"  ... and {len(alive) - 24} more")
        return "\n".join(lines)
    except Exception:
        return ""


def handle_unhandled_exception(exc_type, exc_value, exc_traceback):
    if issubclass(exc_type, KeyboardInterrupt):
        sys.__excepthook__(exc_type, exc_value, exc_traceback)
        return
    try:
        report_path = save_crash_report(exc_type, exc_value, exc_traceback)
        print(f"Severe error captured. Crash report saved to: {report_path}")
    except Exception as report_error:
        print(f"Failed to save crash report: {report_error}")
    sys.__excepthook__(exc_type, exc_value, exc_traceback)


def load_win_rate_stats():
    stats = {}
    try:
        if WIN_RATE_STATS_PATH.exists():
            payload = json.loads(WIN_RATE_STATS_PATH.read_text(encoding="utf-8"))
            if isinstance(payload, dict):
                payload = payload.get("roles", payload)
                if isinstance(payload, dict):
                    for job_name, data in payload.items():
                        if not isinstance(data, dict):
                            continue
                        matches = max(0, int(data.get("matches", 0)))
                        wins = max(0, int(data.get("wins", 0)))
                        stats[job_name] = {"matches": matches, "wins": min(wins, matches)}
    except Exception:
        stats = {}
    for job_name in JOB_DEFS.keys():
        stats.setdefault(job_name, {"matches": 0, "wins": 0})
    return stats


def save_win_rate_stats(stats):
    WIN_RATE_STATS_PATH.write_text(
        json.dumps({"roles": stats}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


def record_win_rate_result(game_state):
    stats = load_win_rate_stats()
    for character in game_state.get("battle_participants", []):
        job_name = getattr(character, "job_name", None)
        if job_name not in JOB_DEFS:
            continue
        stats[job_name]["matches"] += 1
    winner = game_state.get("winner_character")
    if winner is not None and getattr(winner, "job_name", None) in stats:
        stats[winner.job_name]["wins"] += 1
    save_win_rate_stats(stats)


def _settings_path():
    return str(PROJECT_ROOT / "settings.json")


def load_settings():
    default = {
        "volume": 70,
        "effects_quality": "high",
        "skip_entrance": False,
        "fullscreen": False,
        "disable_timed_weapon_drops": True,  # 关闭定时武器掉落：默认常驻开启
    }
    try:
        with open(_settings_path(), "r", encoding="utf-8") as handle:
            data = json.load(handle)
        for key, value in default.items():
            data.setdefault(key, value)
        return data
    except (OSError, ValueError, TypeError):
        return dict(default)


def save_settings(settings):
    try:
        with open(_settings_path(), "w", encoding="utf-8") as handle:
            json.dump(settings, handle, ensure_ascii=False, indent=2)
    except OSError:
        pass


