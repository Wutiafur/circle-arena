BASE_ROLE_ORDER = [n for n in JOB_DEFS.keys() if not n.startswith("DesignRole") and n != "Bloodwraith"]


def get_role_display_number(job_name):
    meta = DESIGN_ROLE_METADATA.get(job_name, {})
    num = meta.get("role_num")
    if num is not None:
        return int(num)
    if job_name == "Bloodwraith":
        return 40
    if job_name in BASE_ROLE_ORDER:
        return BASE_ROLE_ORDER.index(job_name) + 1
    return None


def get_pokedex_ordered_names():
    def sort_key(name):
        num = get_role_display_number(name)
        if num is not None:
            return (0, num)
        return (1, 0)

    return sorted(CHARACTER_DATA.keys(), key=sort_key)


def get_role_attack_tag(job_name, data):
    melee = data.get("attack_type") == "melee"
    prefix = "近" if melee else "远"
    if job_name == DRAGON_JOB_NAME:
        return prefix + "混"
    kind = DESIGN_ROLE_METADATA.get(job_name, {}).get("basic_damage_kind")
    if kind == "spell":
        return prefix + "法"
    if kind == "true":
        return prefix + "真"
    if job_name.startswith("DesignRole"):
        return prefix + "物"
    return prefix


def filter_pokedex_names(ordered_names, query):
    if not query:
        return list(ordered_names)
    q = query.strip().lower()
    out = []
    for name in ordered_names:
        data = get_pokedex_data(name)
        if q in data["display_name"].lower() or q in name.lower():
            out.append(name)
            continue
        # 编号搜索：支持 # 前缀与纯数字
        num = get_role_display_number(name)
        if num is not None:
            if q == str(num) or q == f"#{num}":
                out.append(name)
                continue
            digits = "".join(ch for ch in q if ch.isdigit())
            if digits and digits in str(num):
                out.append(name)
                continue
        # 英文名（CHARACTER_DATA 的原始 name 字段）
        if q in str(data.get("name", "")).lower():
            out.append(name)
            continue
        # 中文技能名 / 技能关键词
        if q in str(data.get("display_skill_name", "")).lower():
            out.append(name)
            continue
        # 攻击方式标签（近 / 远 / 物 / 法 / 真 / 混）
        tag = get_role_attack_tag(name, data)
        if q in tag.lower():
            out.append(name)
            continue
        # 抗性提示语：物抗 / 法抗 数值
        if "物抗" in q and data.get("physical_resistance", 0) >= 1.0:
            out.append(name)
            continue
        if "法抗" in q and data.get("spell_resistance", 0) >= 1.0:
            out.append(name)
            continue
    return out


def pokedex_layout_entries(filtered_names):
    entries = []
    prev_group = None
    for name in filtered_names:
        num = get_role_display_number(name)
        group = "design" if num is not None and num > 40 else "base"
        if group != prev_group:
            entries.append(("header", "基础英雄" if group == "base" else "设计角色"))
            prev_group = group
        entries.append(("row", name))
    return entries
def build_win_rate_rows(body_font, stats):
    rows = []
    for job_name in CHARACTER_DATA.keys():
        data = get_pokedex_data(job_name)
        entry = stats.get(job_name, {"matches": 0, "wins": 0})
        matches = max(0, int(entry.get("matches", 0)))
        wins = max(0, min(matches, int(entry.get("wins", 0))))
        win_rate = (wins / matches * 100.0) if matches > 0 else 0.0
        rows.append(
            {
                "job_name": job_name,
                "display_name": data["display_name"],
                "matches": matches,
                "wins": wins,
                "win_rate": win_rate,
                "shape": data["shape"],
                "color": data["color"],
            }
        )
    rows.sort(key=lambda row: (-row["win_rate"], -row["wins"], -row["matches"], row["display_name"]))
    return rows


def get_top_three_jobs(stats=None, min_matches=3):
    """返回当前胜率排行榜前三的角色 job_name 列表（需至少 min_matches 场才有资格）。"""
    if stats is None:
        stats = load_win_rate_stats()
    candidates = []
    for job_name in CHARACTER_DATA.keys():
        entry = stats.get(job_name, {"matches": 0, "wins": 0})
        matches = max(0, int(entry.get("matches", 0)))
        wins = max(0, min(matches, int(entry.get("wins", 0))))
        if matches < min_matches:
            continue
        win_rate = wins / matches * 100.0
        candidates.append((job_name, win_rate, wins, matches))
    candidates.sort(key=lambda item: (-item[1], -item[2], -item[3], item[0]))
    return [item[0] for item in candidates[:3]]



